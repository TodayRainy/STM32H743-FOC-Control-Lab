uint16_t COMPLEX_VCP_DataRx (uint8_t* Buf, uint32_t Len)
{
	u8 i;
	u8 res;
	for(i=0;i<Len;i++)
	{  
		res=Buf[i]; 
		if((COMPLEX_USB_USART_RX_STA&0x8000)==0)		//?????????
		{
			if(COMPLEX_USB_USART_RX_STA&0x4000)			//???????0x0d
			{
				if(res!=0x0a)COMPLEX_USB_USART_RX_STA=0;//???????,??????
				else COMPLEX_USB_USART_RX_STA|=0x8000;	//????????? 
			}else //??????0X0D
			{	
				if(res==0x0d)COMPLEX_USB_USART_RX_STA|=0x4000;
				else
				{
					COMPLEX_USB_USART_RX_BUF[COMPLEX_USB_USART_RX_STA&0X3FFF]=res;
					COMPLEX_USB_USART_RX_STA++;
					if(COMPLEX_USB_USART_RX_STA>(COMPLEX_USB_USART_REC_LEN-1))COMPLEX_USB_USART_RX_STA=0;//???????????,??????????	
				}					
			}
		}   
	}  
	return USBD_OK;
}

