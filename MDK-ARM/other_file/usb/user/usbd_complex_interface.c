static int8_t COMPLEX_Itf_Control(uint8_t cmd, uint8_t * pbuf, uint16_t length)
{
    switch (cmd)
    {
        case COMPLEX_SEND_ENCAPSULATED_COMMAND:break;
        case COMPLEX_GET_ENCAPSULATED_RESPONSE:break;
        case COMPLEX_SET_COMM_FEATURE:break;
        case COMPLEX_GET_COMM_FEATURE:break;
        case COMPLEX_CLEAR_COMM_FEATURE:break;
        case COMPLEX_SET_LINE_CODING:
            COMPLEX_LineCoding.bitrate = (uint32_t) (pbuf[0] | (pbuf[1] << 8) |
                                     (pbuf[2] << 16) | (pbuf[3] << 24));
            COMPLEX_LineCoding.format = pbuf[4];
            COMPLEX_LineCoding.paritytype = pbuf[5];
            COMPLEX_LineCoding.datatype = pbuf[6];
			//???????????
			printf("linecoding.format:%d\r\n",COMPLEX_LineCoding.format);
			printf("linecoding.paritytype:%d\r\n",COMPLEX_LineCoding.paritytype);
			printf("linecoding.datatype:%d\r\n",COMPLEX_LineCoding.datatype);
			printf("linecoding.bitrate:%d\r\n",COMPLEX_LineCoding.bitrate);
            break;

        case COMPLEX_GET_LINE_CODING:
            pbuf[0] = (uint8_t) (COMPLEX_LineCoding.bitrate);
            pbuf[1] = (uint8_t) (COMPLEX_LineCoding.bitrate >> 8);
            pbuf[2] = (uint8_t) (COMPLEX_LineCoding.bitrate >> 16);
            pbuf[3] = (uint8_t) (COMPLEX_LineCoding.bitrate >> 24);
            pbuf[4] = COMPLEX_LineCoding.format;
            pbuf[5] = COMPLEX_LineCoding.paritytype;
            pbuf[6] = COMPLEX_LineCoding.datatype;
            break;

        case COMPLEX_SET_CONTROL_LINE_STATE:break;
        case COMPLEX_SEND_BREAK:break;
        default:break;
    }
    return (USBD_OK);
}


